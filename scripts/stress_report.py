"""The assistant stress test's reports from its runs (docs/ASSISTANT_STRESS_PLAN.md T4): `results.md` (each
conversation's verdict, turns, cost and latency, with links to its transcript) and `coverage.md` (each BRD
requirement the catalogue touches, with the conversations that test it and how they ended).

    .venv/bin/python scripts/stress_report.py --run final --run final-fail
    .venv/bin/python scripts/stress_report.py --dir docs/brd/testing/assistant/staff --name "The staff assistant \
        stress test" --run final --run final-fail                            (the staff roles: STAFF_STRESS_PLAN.md)
"""

from __future__ import annotations

import argparse
import json
import statistics
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parents[1] / "docs" / "brd" / "testing" / "assistant"
NAME = "The assistant stress test"


def review() -> dict:
    """My verdicts by hand where they differ from the machine's (``review.json``), each with its reason."""
    path = HERE / "review.json"
    return json.loads(path.read_text())["conversations"] if path.exists() else {}


def held(r: dict, hand: dict) -> bool:
    return hand[r["id"]]["ok"] if r["id"] in hand else r["ok"]


def load(tags):
    cat = {c["id"]: c for c in json.loads((HERE / "catalogue.json").read_text())["conversations"]}
    rows, turns = {}, []
    for tag in tags:
        res = json.loads((HERE / "runs" / tag / "results.json").read_text())
        for r in res["conversations"]:
            rows[r["id"]] = {**r, "tag": tag}
            path = HERE / "runs" / tag / f"{r['id']}.json"
            if path.exists():
                turns += [t for t in json.loads(path.read_text())["run"] if t.get("answer")]
    return cat, rows, turns


def results_md(cat, rows, turns, tags, hand) -> str:
    cost = sum(r["cost"] for r in rows.values())
    by_hand = sum(held(r, hand) for r in rows.values())
    secs = [t["seconds"] for t in turns if t.get("seconds")]
    first = [t["first_event"] for t in turns if t.get("first_event")]
    passed = sum(r["ok"] for r in rows.values())
    n_turns = sum(r["turns"] for r in rows.values())
    failed_turns = sum(len(r["failed"]) for r in rows.values())
    out = [
        f"# {NAME} — results",
        "",
        f"Generated by `scripts/stress_report.py` from the runs {', '.join(f'`{t}`' for t in tags)} "
        "(`runs/<tag>/`: a JSON record and a Markdown transcript per conversation). The verdict is the machine "
        "checks'; every transcript was also read by hand (defects.md says what that found).",
        "",
        f"- **Conversations:** {passed} of {len(rows)} passed every check; **turns:** {n_turns - failed_turns} of "
        f"{n_turns}. **By hand** (review.json, defects.md): {by_hand} of {len(rows)} behaved correctly.",
        f"- **Cost of these runs:** US${cost:.4f} (model and tools, as each answer reports it).",
        f"- **Latency per turn:** median {statistics.median(secs):.1f} s, p90 "
        f"{sorted(secs)[int(len(secs) * 0.9) - 1]:.1f} s; first event median {statistics.median(first):.1f} s."
        if secs and first
        else "",
        "",
        "| Conversation | Category | Turns | Machine checks | By hand | Cost (US$) | Seconds |",
        "|---|---|---|---|---|---|---|",
    ]
    for cid, c in cat.items():
        r = rows.get(cid)
        if not r:
            out.append(f"| {cid} — {c['title']} | {c['category']} | {len(c['turns'])} | not run | — | — | — |")
            continue
        verdict = "pass" if r["ok"] else "fail: " + "; ".join(f"turn {i}: {', '.join(w)}" for i, w in r["failed"])
        link = f"[{cid}](runs/{r['tag']}/{cid}.md)"
        mine = (("correct" if hand[cid]["ok"] else "defect") + ": " + hand[cid]["why"]) if cid in hand else "agrees"
        out.append(f"| {link} — {c['title']} | {c['category']} | {r['turns']} | {verdict.replace('|', '¦')} | "
                   f"{mine.replace('|', '¦')} | {r['cost']:.4f} | {r['seconds']:.0f} |")  # fmt: skip
    return "\n".join(x for x in out if x is not None) + "\n"


def coverage_md(cat, rows, hand) -> str:
    by = defaultdict(list)
    for cid, c in cat.items():
        for b in c.get("brd", []):
            by[b].append(cid)
    out = [
        f"# {NAME} — coverage of the BRD",
        "",
        "Each requirement the catalogue's conversations name (`brd` in `catalogue.json`), with the conversations "
        "that test it and their verdicts. A requirement is *exercised* when at least one conversation ran; *held* "
        "when every one of them behaved correctly, by hand where my review differs from the machine checks "
        "(review.json; ✗ marks a conversation that did not).",
        "",
        "| Requirement | Conversations | Held |",
        "|---|---|---|",
    ]
    for b in sorted(by):
        ids = by[b]
        ran = [rows[i] for i in ids if i in rows]
        bad = sum(not held(r, hand) for r in ran)
        verdict = "—" if not ran else "yes" if not bad else f"no ({bad})"
        cells = ", ".join(f"{i}{'' if i in rows and held(rows[i], hand) else ' ✗' if i in rows else ' (not run)'}"
                          for i in ids)  # fmt: skip
        out.append(f"| {b} | {cells} | {verdict} |")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--run", action="append", required=True, help="a run tag (repeat: later ones win)")
    ap.add_argument("--dir", default=str(HERE), help="the test's folder: catalogue.json, review.json, runs/")
    ap.add_argument("--name", default=NAME, help="the reports' title")
    a = ap.parse_args()
    globals().update(HERE=Path(a.dir).resolve(), NAME=a.name)
    cat, rows, turns = load(a.run)
    hand = review()
    (HERE / "results.md").write_text(results_md(cat, rows, turns, a.run, hand))
    (HERE / "coverage.md").write_text(coverage_md(cat, rows, hand))
    print(f"{sum(r['ok'] for r in rows.values())}/{len(rows)} by the machine checks, "
          f"{sum(held(r, hand) for r in rows.values())} by hand; results.md, coverage.md written")  # fmt: skip


if __name__ == "__main__":
    main()
